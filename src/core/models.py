"""Core entities shared across pipeline stages (PRD §10).

FR1 adds the validated CLI input; FR2 adds the extracted fund data; FR3 adds
the searched news; FR4 adds the synthesized report sections.
"""

from dataclasses import dataclass
@dataclass(frozen=True)
class RunInput:
    """Validated CLI input (PRD FR1): fund name."""

    fund: str


@dataclass(frozen=True)
class Holding:
    """One fund holding (PRD §10): name, Yahoo symbol, weight as a percent
    value in [0, 100] — 10 means 10% (FR2 boundary normalization)."""

    name: str
    symbol: str
    weight: float


@dataclass(frozen=True)
class FundProfile:
    """Extracted fund data (PRD FR2, contracts/yahoo.v1.md).

    Every percent-denominated value is a percent value — 10 means 10%,
    never 0.1: `holdings[].weight` and `sector_weights` are percents in
    [0, 100], and the ratio fields of `overview` (`expenseRatio`, `yield`,
    `ytdReturn`, the three-/five-year averages, the 3-month trailing
    return, `dividendYield`, `annualHoldingsTurnover`) are percents too.
    Amounts (`totalAssets`, `navPrice`, `dividendRate`) stay in the fund's
    currency; rendering them (2.15 billion) is the FR4/FR5 presentation
    concern. `beta3Year` and the Morningstar ratings are unitless and pass
    through untouched. Yahoo labels the `beta3Year` API field as
    "Beta (5Y monthly)"; that reader-facing label is used in the report.
    `inception` is an ISO date and `category` the
    Morningstar category name.

    `gaps` records data Yahoo did not return; the report (FR5) must surface
    the report (FR5) must surface them instead of inventing numbers.
    """

    fund: str
    ticker: str
    name: str
    provider: str
    family: str | None
    currency: str | None
    holdings: tuple[Holding, ...]
    sector_weights: dict[str, float]
    overview: dict[str, float | int | str]
    gaps: tuple[str, ...]


@dataclass(frozen=True)
class NewsItem:
    """One searched news result (PRD §10, contracts/exa.v1.md).

    `relevance` is the item's 1-based rank within its originating search (Exa
    spec 2.0.0 returns no per-result score); `related` names the holding or
    sector the query targeted — the news is only ever news *about what the
    fund holds*. `summary` is Exa's generated digest and `content` the
    result's page text (first 10000 characters; both requested per search).
    """

    title: str
    url: str
    source: str
    published: str | None
    summary: str | None
    content: str | None
    relevance: int
    related: tuple[str, ...]


@dataclass(frozen=True)
class ReportSections:
    """Synthesized report sections (PRD FR4, contracts/ollama.v1.md).

    The two FR4 sections written by the LLM, validated at the boundary:
    both present and non-empty, English-only per the prompt, and written in
    simple language. Fund-level metrics in the final report are assembled from
    FundProfile by FR5, not generated by the LLM.
    """

    company_insights: str
    sector_insights: str
